    private static let anchorBS = BSDate(year: 1978, month: 1, day: 1)
    /// 1921-04-13, the AD date of 1978-01-01 BS.
    private static let anchorAD: Date = {
        var c = DateComponents()
        c.year = 1921; c.month = 4; c.day = 13
        return Calendar(identifier: .gregorian).date(from: c)!
    }()

    static var minYear: Int { monthLengths.keys.min()! }
    static var maxYear: Int { monthLengths.keys.max()! }

    /// AD → BS. Nil when the date is outside the table's coverage.
    static func bsDate(from date: Date, calendar: Calendar = .current) -> BSDate? {
        var greg = Calendar(identifier: .gregorian)
        greg.timeZone = calendar.timeZone
        let start = greg.startOfDay(for: anchorAD)
        let end = greg.startOfDay(for: date)
        let days = greg.dateComponents([.day], from: start, to: end).day ?? 0
        guard days >= 0 else { return nil }

        var remaining = days
        var year = anchorBS.year
        while let months = monthLengths[year] {
            let yearDays = months.reduce(0, +)
            if remaining < yearDays { break }
            remaining -= yearDays
            year += 1
        }
        guard let months = monthLengths[year] else { return nil }

        var month = 1
        for length in months {
            if remaining < length { break }
            remaining -= length
            month += 1
        }
        return BSDate(year: year, month: month, day: remaining + 1)
    }

    /// BS → AD. Nil when out of coverage or the date is invalid for its
    /// year/month (e.g. day 32 in a 31-day month).
    static func adDate(from bs: BSDate, calendar: Calendar = .current) -> Date? {
        guard let months = monthLengths[bs.year],
              (1...12).contains(bs.month),
              bs.day >= 1, bs.day <= months[bs.month - 1] else { return nil }

        var days = 0
        for y in anchorBS.year..<bs.year {
            guard let yearMonths = monthLengths[y] else { return nil }
            days += yearMonths.reduce(0, +)
        }
        for m in 0..<(bs.month - 1) { days += months[m] }
        days += bs.day - 1

        var greg = Calendar(identifier: .gregorian)
        greg.timeZone = calendar.timeZone
        return greg.date(byAdding: .day, value: days,
                         to: greg.startOfDay(for: anchorAD))
    }

